foreach ($key in $imagesToUpdate.Keys) {
    $url = $imagesToUpdate[$key]
    $destImg = $key
    $destImages = $key -replace '^img', 'Images'
    
    $parentImg = Split-Path $destImg -Parent
    $parentImages = Split-Path $destImages -Parent
    if (-not (Test-Path $parentImg)) { New-Item -ItemType Directory -Force -Path $parentImg | Out-Null }
    if (-not (Test-Path $parentImages)) { New-Item -ItemType Directory -Force -Path $parentImages | Out-Null }
    
    try {
        Invoke-WebRequest -Uri $url -OutFile $destImg -TimeoutSec 6 -UseBasicParsing
        Copy-Item $destImg $destImages -Force
        Write-Host "Updated: $key"
    } catch {
        Write-Host "Failed: $key -> $($_.Exception.Message)"
    }
}
